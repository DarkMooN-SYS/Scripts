$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$modules = @(
    @{ Name = 'Theme'; Path = 'UI\Theme.lua' },
    @{ Name = 'Components'; Path = 'UI\Components.lua' },
    @{ Name = 'Window'; Path = 'UI\Window.lua' },
    @{ Name = 'Dashboard'; Path = 'UI\Dashboard.lua' },
    @{ Name = 'Debug'; Path = 'UI\Debug.lua' },
    @{ Name = 'Auth'; Path = 'UI\Auth.lua' },
    @{ Name = 'GameConfig139'; Path = 'Games\139542527731344\Config.lua' },
    @{ Name = 'GameFeatures139'; Path = 'Games\139542527731344\Features.lua' },
    @{ Name = 'Game139'; Path = 'Games\139542527731344\init.lua' }
)

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('-- Generated by build.ps1. Edit UI source files and rebuild.')
$lines.Add('-- Bundled menu, authorization, and place-specific modules.')
$lines.Add('')
foreach ($module in $modules) {
    $lines.Add("local $($module.Name) = (function()")
    $lines.Add((Get-Content -LiteralPath (Join-Path $root $module.Path) -Raw).TrimEnd())
    $lines.Add('end)()')
    $lines.Add('')
}
$lines.Add('local menu = Window.new({Name = "MooN_HUB_Menu", Title = "MooN | HUB"})')
$lines.Add('Dashboard.Configure(menu)')
$lines.Add('Debug.Configure(menu)')
$lines.Add('Auth.Configure(menu, function()')
$lines.Add('    if game.PlaceId == GameConfig139.PlaceId then')
$lines.Add('        Game139.Configure(menu)')
$lines.Add('    end')
$lines.Add('end)')
$lines.Add('')
Set-Content -LiteralPath (Join-Path $root 'main.lua') -Value ($lines -join [Environment]::NewLine) -Encoding utf8
Write-Output "Built main.lua from UI source modules."
